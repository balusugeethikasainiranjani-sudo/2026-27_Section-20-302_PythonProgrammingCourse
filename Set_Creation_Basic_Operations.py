# Create a set
my_set = {10, 20, 30, 40, 50}

# Display the set
print("Original Set:", my_set)

# Add an element
my_set.add(60)
print("After Adding:", my_set)

# Remove an element
my_set.remove(30)
print("After Removing:", my_set)

# Find length
print("Length of Set:", len(my_set))

# Check an element
print("Is 20 present?", 20 in my_set)

# Remove all elements
my_set.clear()
print("After Clearing:", my_set)