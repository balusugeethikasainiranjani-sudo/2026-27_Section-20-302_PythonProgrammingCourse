# Create a tuple
my_tuple = (10, 20, 30, 40, 50)

# Display tuple
print("Original Tuple:", my_tuple)

# Access elements
print("First Element:", my_tuple[0])

# Find length
print("Length:", len(my_tuple))

# Count elements
print("Count of 20:", my_tuple.count(20))

# Find index
print("Index of 30:", my_tuple.index(30))

# Slicing
print("Sliced Tuple:", my_tuple[1:4])

# Concatenation
tuple2 = (60, 70)
print("Concatenation:", my_tuple + tuple2)

# Repetition
print("Repetition:", my_tuple * 2)

# Membership
print("Is 30 present?", 30 in my_tuple)